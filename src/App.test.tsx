import { afterEach, beforeEach, expect, test } from 'vitest';
import { cleanup, fireEvent, render, screen } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import App from './App';
beforeEach(() => {
 localStorage.clear(); window.history.replaceState(null, '', '#plan');
 Object.defineProperty(window,'matchMedia',{writable:true,value:()=>({matches:false,addListener:()=>{},removeListener:()=>{},addEventListener:()=>{},removeEventListener:()=>{}})});
});
afterEach(cleanup);
test('starts with the itinerary and advances from Exchange Regency to individual museums', async () => {
 const user=userEvent.setup(); const view=render(<App/>);
 expect(screen.getByRole('heading',{name:/A Day Around/})).toBeTruthy();
 expect(screen.getByText(/Exchange Regency, Ortigas/)).toBeTruthy();
 expect(screen.queryByRole('heading',{name:'National Museum of Natural History'})).toBeNull();
 await user.click(screen.getByRole('button',{name:'Next: Getting there'}));
 expect(window.location.hash).toBe('#journey');
 expect(screen.getByRole('heading',{name:/meet you at your condo/})).toBeTruthy();
 await user.click(screen.getByRole('button',{name:'MRT Shaw Boulevard'}));
 expect(localStorage.getItem('museumdate:station')).toBe('"Shaw Boulevard"');
 expect(screen.getByRole('heading',{name:'Ride to MRT Shaw Boulevard'})).toBeTruthy();
 await user.click(screen.getByRole('button',{name:'Next: Natural History'}));
 expect(screen.getByRole('heading',{name:'National Museum of Natural History'})).toBeTruthy();
 expect(screen.queryByRole('heading',{name:'National Museum of Anthropology'})).toBeNull();
 await user.click(screen.getByRole('button',{name:'Next: Anthropology'}));
 expect(screen.getByRole('heading',{name:'National Museum of Anthropology'})).toBeTruthy();
 window.history.replaceState(null,'','#journey'); fireEvent.popState(window);
 expect(screen.getByRole('heading',{name:'Ride to MRT Shaw Boulevard'})).toBeTruthy();
 view.unmount(); render(<App/>);
 expect(screen.getByRole('heading',{name:'Ride to MRT Shaw Boulevard'})).toBeTruthy();
});
test('museum details, favorites, lunch and RSVP survive page changes and remount', async () => {
 const user=userEvent.setup(); const view=render(<App/>);
 const jump=()=>screen.getByRole('combobox',{name:'Go to trip page'});
 await user.selectOptions(jump(),'natural');
 await user.click(screen.getByRole('button',{name:'Save Tree of Life as favorite'}));
 await user.click(screen.getByRole('button',{name:/See Museum Highlights/}));
 expect(screen.getByRole('heading',{name:'Philippine Biodiversity'})).toBeTruthy();
 await user.click(screen.getByRole('button',{name:'Photo & Mission'}));
 const duration=screen.getByRole('textbox',{name:/Estimated Visit/});
 await user.clear(duration); await user.type(duration,'90 minutes');
 await user.click(screen.getByRole('checkbox',{name:/Find the Tree of Life/}));
 await user.selectOptions(jump(),'lunch');
 await user.click(screen.getByRole('button',{name:'Ilustrado'}));
 await user.selectOptions(jump(),'rsvp');
 await user.click(screen.getByRole('button',{name:/Yes, I/}));
 expect(screen.getByRole('heading',{name:/a Date!/})).toBeTruthy();
 await user.selectOptions(jump(),'favorites');
 expect(screen.getByRole('heading',{name:'Tree of Life'})).toBeTruthy();
 view.unmount(); render(<App/>);
 expect(screen.getByRole('heading',{name:'Tree of Life'})).toBeTruthy();
 await user.selectOptions(jump(),'lunch');
 expect(screen.getByRole('button',{name:/Ilustrado/}).getAttribute('aria-pressed')).toBe('true');
 await user.selectOptions(jump(),'natural');
 await user.click(screen.getByRole('button',{name:'Photo & Mission'}));
 expect((screen.getByRole('textbox',{name:/Estimated Visit/}) as HTMLInputElement).value).toBe('90 minutes');
 expect((screen.getByRole('checkbox',{name:/Find the Tree of Life/}) as HTMLInputElement).checked).toBe(true);
 await user.selectOptions(jump(),'pass');
 expect(screen.getByText('Exchange Regency, Ortigas')).toBeTruthy();
 await user.selectOptions(jump(),'rsvp');
 expect(screen.getByRole('heading',{name:/a Date!/})).toBeTruthy();
});
test('unknown links and invalid stored choices fall back safely', async () => {
 window.history.replaceState(null,'','#unknown-page');
 localStorage.setItem('museumdate:favorites','{broken');
 localStorage.setItem('museumdate:lunch','{"unexpected":true}');
 localStorage.setItem('museumdate:rsvp','123');
 localStorage.setItem('museumdate:station','"invalid"');
 render(<App/>);
 expect(screen.getByRole('heading',{name:/A Day Around/})).toBeTruthy();
 await userEvent.setup().selectOptions(screen.getByRole('combobox',{name:'Go to trip page'}),'journey');
 expect(screen.getByRole('heading',{name:'Ride to MRT Ortigas'})).toBeTruthy();
});
